export function nodeFromPalette(item: (typeof PALETTE)[number], index: number): FlowNode {
  return {
    id: `${item.id}-${index}`,
    index,
    title: item.title,
    venue: item.venue,
    chain: item.chain,
    service: item.service,
    input: item.input,
    output: item.output,
    trigger: item.input === "none" ? { when: "manual" } : { when: "now" },
    routes: [],
    params: [{ label: "Catalog", value: `${item.id} on commit 9608b9df. Not installed on a vault.` }],
    position: { x: 80 + (index % 4) * 40, y: 80 + index * 24 },
    serializable: item.serializable,
    catalogId: item.id,
  };
}
