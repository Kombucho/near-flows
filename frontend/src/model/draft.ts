const E24 = 10n ** 24n;

function price(usd: number): string {
  return (BigInt(usd) * E24).toString();
}

function n(partial: Omit<FlowNode, "params"> & { params?: FlowNode["params"] }): FlowNode {
  return { params: [], ...partial };
}

